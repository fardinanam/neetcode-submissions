SELECT c.CUSTOMER_ID, c.CUSTOMER_NAME FROM CUSTOMERS c
WHERE 'A' IN (
    SELECT PRODUCT_NAME FROM ORDERS WHERE CUSTOMER_ID = c.CUSTOMER_ID
) AND 'B' IN (
    SELECT PRODUCT_NAME FROM ORDERS WHERE CUSTOMER_ID = c.CUSTOMER_ID
) AND 'C' NOT IN (
    SELECT PRODUCT_NAME FROM ORDERS WHERE CUSTOMER_ID = c.CUSTOMER_ID
)
ORDER BY C.CUSTOMER_NAME;