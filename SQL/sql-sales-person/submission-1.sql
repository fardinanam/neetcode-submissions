WITH SC AS (
    SELECT S.SALES_ID AS SID, S.NAME AS S_NAME, C.NAME AS C_NAME
    FROM SALES_PERSON S
    LEFT JOIN ORDERS O
        ON S.SALES_ID = O.SALES_ID
    LEFT JOIN COMPANY C
        ON O.COM_ID = C.COM_ID
)
SELECT DISTINCT SC1.S_NAME NAME
FROM SC SC1
WHERE SC1.SID NOT IN (
    SELECT DISTINCT SC2.SID
    FROM SC SC2
    WHERE SC2.C_NAME = 'CRIMSON'
)
ORDER BY SC1.S_NAME;